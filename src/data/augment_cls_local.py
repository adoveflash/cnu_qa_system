def generate_from_templates(
    topics: list[str],
    patterns: list[str],
    freeform: list[str],
    target: int,
) -> list[str]:
    """주제 × 패턴 조합 + 자유형 질문으로 목표 개수만큼 생성."""
    questions: list[str] = []

    # 1) 모든 조합 생성
    combos = list(itertools.product(topics, patterns))
    random.shuffle(combos)
    for topic, pattern in combos:
        q = pattern.format(topic=topic)
        questions.append(q)

    # 2) 자유형 추가
    questions.extend(freeform)

    # 3) 부족하면 말투 변형으로 추가 생성
    suffixes_polite = ["요", "요?", "나요?", "까요?", "세요?", "습니다", "ㅂ니다"]
    suffixes_casual = ["?", "야?", "어?", "냐?", "지?", "ㅋ", "ㅎ"]
    prefixes = [
        "",
        "혹시 ",
        "그런데 ",
        "근데 ",
        "저기 ",
        "저 ",
        "실례지만 ",
        "궁금한데 ",
        "질문인데 ",
        "하나만 물어볼게 ",
        "잠깐만 ",
    ]

    base_set = list(questions)
    random.shuffle(base_set)
    idx = 0
    while len(questions) < target:
        base = base_set[idx % len(base_set)]
        prefix = random.choice(prefixes)
        # 말투 변형
        variant = prefix + base
        # 어미 변형
        if random.random() < 0.3:
            for s in suffixes_polite:
                if variant.endswith(s):
                    variant = variant[: -len(s)] + random.choice(suffixes_casual)
                    break
        elif random.random() < 0.3:
            for s in suffixes_casual:
                if variant.endswith(s):
                    variant = variant[: -len(s)] + random.choice(suffixes_polite)
                    break
        questions.append(variant)
        idx += 1

    return questions


def deduplicate(questions: list[str]) -> list[str]:
    """정규화 후 중복 제거."""
    seen: set[str] = set()
    result = []
    for q in questions:
        normalized = q.strip().lower().replace(" ", "")
        if normalized not in seen and len(q.strip()) > 3:
            seen.add(normalized)
            result.append(q.strip())
    return result


